import { test, expect } from './fixtures'
import { mkdir } from 'node:fs/promises'

test('new entry expands on typing and collapses on clearing while preserving undo and drafts', async ({ page, request }) => {
  await page.setViewportSize({ width: 1440, height: 1040 })
  await page.goto('/')
  const amount = page.locator('#amount')
  const note = page.getByLabel('Nội dung', { exact: true })
  const save = page.getByRole('button', { name: 'Ghi giao dịch', exact: true })
  const clear = page.getByRole('button', { name: 'Xóa số tiền', exact: true })
  await expect(amount).toBeVisible()
  await expect(note).toBeHidden()
  await expect(save).toBeHidden()
  await expect(page.getByLabel('Tỷ giá USD', { exact: true })).toBeHidden()
  await expect(clear).toHaveCount(0)
  await mkdir('.tmp', { recursive: true })
  await page.screenshot({ path: '.tmp/entry-collapsed-desktop.png', fullPage: true })
  await amount.fill('0')
  await expect(note).toBeVisible()
  await expect(save).toBeDisabled()
  await amount.fill('')
  await expect(note).toBeHidden()
  await amount.fill('$1.50')
  await note.fill('Collapsed form amount reset')
  await expect(page.locator('.amount-usd-hint')).toHaveText('$1,50')
  const iconBox = await clear.boundingBox()
  const inputBox = await amount.boundingBox()
  const leftPadding = await amount.evaluate(element => parseFloat(getComputedStyle(element).paddingLeft))
  expect(iconBox!.x + iconBox!.width).toBeLessThanOrEqual(inputBox!.x + leftPadding)
  await page.screenshot({ path: '.tmp/entry-expanded-desktop.png', fullPage: true })
  await clear.click()
  await expect(amount).toHaveValue('')
  await expect(amount).toBeFocused()
  await expect(note).toBeHidden()
  await amount.press('Meta+z')
  await expect(note).toBeVisible()
  await expect(note).toHaveValue('Collapsed form amount reset')
  await expect(page.locator('.amount-usd-hint')).toHaveText('$1,50')
  await amount.press('Meta+Shift+z')
  await expect(amount).toHaveValue('')
  await expect(note).toBeHidden()
  await page.setViewportSize({ width: 375, height: 812 })
  await page.screenshot({ path: '.tmp/entry-collapsed-mobile.png', fullPage: true })
  await amount.fill('+500')
  await expect(page.locator('.amount-usd-hint')).toHaveCount(0)
  await expect(note).toHaveValue('Collapsed form amount reset')
  await save.click()
  await expect(amount).toHaveValue('')
  await expect(note).toBeHidden()
  const state = await (await request.get('/api/state')).json()
  const saved = state.transactions.find((transaction: { note: string }) => transaction.note === 'Collapsed form amount reset')
  expect(saved.amount).toBe('500')
  expect(saved.usd_minor).toBe('')
  await request.delete('/api/transactions/' + saved.id)
})
